import { cpSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { root, prepareProduction } from './production.mjs';
import { spawnSync } from 'node:child_process';
const stage = prepareProduction();
const output = resolve(root, 'dist');
const require = createRequire(import.meta.url);
const useZeus = process.argv.includes('--zeus');
const cli = useZeus ? resolve(root, 'scripts/zeus.cjs') : resolve(dirname(require.resolve('@zeppos/zpm/package.json')), 'bin/index.js');
const args = useZeus ? [cli, 'build', '--target', 'Amazfit Bip 6'] : [cli, 'build', '-p', stage, '-t', 'bip6', '--jsc', 'bin', '--prune', 'true', '--compress', 'true', '--ip', 'false', '--sources', '9765120', '9765121', '10158337'];
const result = spawnSync(process.execPath, args, { cwd: stage, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
const built = resolve(stage, 'dist');
const artifacts = existsSync(built) ? readdirSync(built).filter((name) => name.endsWith('.zab')) : [];
if (!artifacts.length) throw new Error('O compilador não gerou um pacote .zab válido.');
mkdirSync(output, { recursive: true });
for (const name of readdirSync(output).filter((name) => name.endsWith('.zab'))) rmSync(resolve(output, name));
for (const name of artifacts) cpSync(resolve(built, name), resolve(output, name));
process.stdout.write(`Pacote gerado: ${artifacts.map((name) => `dist/${name}`).join(', ')}\n`);
